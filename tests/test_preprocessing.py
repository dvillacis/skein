def test_polychoric_recovers_known_rho_on_5_level_likert():
    """Olsson two-step ML should recover the latent Gaussian
    correlation to within 0.05 at n=2000 with 5-level Likert."""
    rng = np.random.default_rng(0)
    p = 4
    true_R = np.array([
        [1.0, 0.6, 0.3, 0.0],
        [0.6, 1.0, 0.4, 0.2],
        [0.3, 0.4, 1.0, 0.5],
        [0.0, 0.2, 0.5, 1.0],
    ])
    L = np.linalg.cholesky(true_R)
    Z = rng.standard_normal((2000, p)) @ L.T
    thresholds = np.array([-1.0, -0.3, 0.3, 1.0])
    X = _discretize(Z, thresholds)
    R = polychoric_correlation(X)
    np.testing.assert_array_equal(np.diag(R), np.ones(p))
    assert np.max(np.abs(R - R.T)) < 1e-10  # symmetric
    assert np.max(np.abs(R - true_R)) < 0.05


def test_polychoric_recovers_strong_correlation_at_binary():
    """2-level (binary) case reduces to tetrachoric; should still
    recover a strong planted correlation."""
    rng = np.random.default_rng(1)
    n = 5000
    z = rng.multivariate_normal([0, 0], [[1, 0.7], [0.7, 1]], size=n)
    X = (z > 0).astype(int)  # binary
    R = polychoric_correlation(X)
    assert abs(R[0, 1] - 0.7) < 0.05


def test_polychoric_zero_correlation():
    rng = np.random.default_rng(2)
    n = 3000
    z = rng.standard_normal((n, 2))  # uncorrelated
    X = _discretize(z, np.array([-0.5, 0.5]))
    R = polychoric_correlation(X)
    assert abs(R[0, 1]) < 0.05


