"""Tests for `skein_glm.preprocessing` — polychoric / polyserial /
mixed correlation matrices for ordinal data.

Coverage:
- Recovery on synthetic ordinal data generated from a known continuous
  Gaussian: discretize via threshold sets, recover the true ρ to
  ≤ 0.05 absolute error at n=2000.
- Polyserial: same recovery test for ordinal × continuous.
- Mixed pipeline auto-detects column type and produces a valid
  correlation matrix.
- Edge cases: degenerate column (single observed level), tiny pair
  sample size, NaN / pairwise deletion.
- Properties: diagonal exactly 1, off-diagonal symmetric, bounded
  in [-1, 1].
- R-anchor: skipped if `tests/fixtures/psych_polychoric.json` is
  absent (the fixture is generated by `tests/fixtures/generate.R`
  via `psych::polychoric` and committed when available).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

skein = pytest.importorskip("skein_glm")

from skein_glm.preprocessing import (  # noqa: E402
    polychoric_correlation,
    polychoric_covariance_matrix,
    polyserial_correlation,
)


def _correlation_from_pd_matrix(p: int, rho_values: np.ndarray, seed: int) -> np.ndarray:
    """Build a random positive-definite p×p correlation matrix."""
    rng = np.random.default_rng(seed)
    A = rng.standard_normal((p, p))
    R = A @ A.T
    d = np.sqrt(np.diag(R))
    R = R / np.outer(d, d)
    return R


def _draw_latent_gaussian(R: np.ndarray, n: int, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    return rng.multivariate_normal(np.zeros(R.shape[0]), R, size=n)


def _discretize(z: np.ndarray, thresholds: np.ndarray) -> np.ndarray:
    """Bucket continuous z into integer levels via thresholds."""
    return np.digitize(z, thresholds)


