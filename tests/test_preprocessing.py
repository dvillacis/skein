def test_polychoric_diag_is_one_and_symmetric():
    rng = np.random.default_rng(8)
    X = _discretize(rng.standard_normal((400, 5)), np.array([-0.5, 0.5]))
    R = polychoric_correlation(X)
    np.testing.assert_array_equal(np.diag(R), np.ones(5))
    np.testing.assert_allclose(R, R.T, atol=1e-12)
    assert R.min() >= -1.0 and R.max() <= 1.0


def test_polychoric_pairwise_deletion_with_nan():
    rng = np.random.default_rng(9)
    n = 1000
    rho = 0.5
    z = rng.multivariate_normal([0, 0], [[1, rho], [rho, 1]], size=n)
    X = _discretize(z, np.array([-0.5, 0.5])).astype(float)
    # Punch holes in column 0.
    X[::10, 0] = np.nan
    R = polychoric_correlation(X, missing="pairwise")
    assert np.isfinite(R[0, 1])
    assert abs(R[0, 1] - rho) < 0.1  # looser; we dropped 10% of rows


def test_polychoric_listwise_deletion():
    rng = np.random.default_rng(10)
    n = 1500
    z = rng.multivariate_normal([0, 0], [[1, 0.5], [0.5, 1]], size=n)
    X = _discretize(z, np.array([-0.5, 0.5])).astype(float)
    X[::20, 0] = np.nan
    R_listwise = polychoric_correlation(X, missing="listwise")
    assert np.isfinite(R_listwise[0, 1])


def test_polychoric_rejects_invalid_shape():
    with pytest.raises(ValueError, match="2D"):
        polychoric_correlation(np.array([1, 2, 3]))
    with pytest.raises(ValueError, match="at least 2 columns"):
        polychoric_correlation(np.array([[1], [2], [3]]))


