_FIXTURE = Path(__file__).parent / "fixtures" / "psych_polychoric.json"


def test_polychoric_matches_r_psych():
    """Agreement with R `psych::polychoric` to ≤ 5e-3 elementwise on a
    fixed-seed problem. Skipped if the fixture is absent — fixture is
    generated by `Rscript tests/fixtures/generate.R` (when R + psych
    are available) and committed to the repo."""
    if not _FIXTURE.is_file():
        pytest.skip(
            f"fixture {_FIXTURE.name} missing; run `Rscript tests/fixtures/"
            "generate.R` to generate (requires R + psych package)"
        )
    with open(_FIXTURE) as f:
        fix = json.load(f)
    X = np.asarray(fix["X"], dtype=np.int64)
    R_r = np.asarray(fix["R"], dtype=np.float64)
    R = polychoric_correlation(X)
    np.testing.assert_allclose(R, R_r, atol=5e-3)
