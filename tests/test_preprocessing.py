def test_polychoric_covariance_matrix_auto_dispatches():
    """Mixed pipeline auto-detects continuous (>10 unique values) vs
    ordinal columns and produces a recovered correlation within 0.05
    of the latent truth."""
    rng = np.random.default_rng(5)
    p = 4
    true_R = np.array([
        [1.0, 0.6, 0.3, 0.0],
        [0.6, 1.0, 0.4, 0.2],
        [0.3, 0.4, 1.0, 0.5],
        [0.0, 0.2, 0.5, 1.0],
    ])
    L = np.linalg.cholesky(true_R)
    Z = rng.standard_normal((2000, p)) @ L.T
    # Discretize cols 0, 1 to 5-level; leave cols 2, 3 continuous.
    thresholds = np.array([-1.0, -0.3, 0.3, 1.0])
    X = Z.copy()
    X[:, 0] = _discretize(Z[:, 0], thresholds)
    X[:, 1] = _discretize(Z[:, 1], thresholds)
    R = polychoric_covariance_matrix(X)
    np.testing.assert_array_equal(np.diag(R), np.ones(p))
    assert np.max(np.abs(R - R.T)) < 1e-10
    assert np.max(np.abs(R - true_R)) < 0.05


def test_polychoric_covariance_matrix_explicit_mask():
    """Explicit continuous_mask overrides auto-detection."""
    rng = np.random.default_rng(6)
    n, p = 500, 3
    X = rng.standard_normal((n, p))
    # Force middle column to be treated as ordinal even though it's
    # continuous → its polychoric correlation should still be close to
    # the Pearson value (Olsson works on the marginal CDF, which is
    # well-defined for any distribution).
    R = polychoric_covariance_matrix(
        X, continuous_mask=[True, False, True]
    )
    assert R.shape == (p, p)
    np.testing.assert_array_equal(np.diag(R), np.ones(p))


def test_polychoric_covariance_matrix_feeds_graphical_lasso():
    """End-to-end smoke test: mixed correlation matrix → GraphicalLasso.

    Demonstrates the headline pipeline for psychometrics. We don't
    assert on the precision matrix content here (that's covered by
    the network-recovery tests in test_graph_stability.py); we just
    confirm the API plumbing accepts the polychoric output."""
    rng = np.random.default_rng(7)
    n = 800
    rho = 0.6
    z = rng.multivariate_normal([0, 0, 0], [[1, rho, 0], [rho, 1, 0.3], [0, 0.3, 1]], size=n)
    X = z.copy()
    X[:, 0] = _discretize(z[:, 0], np.array([-0.5, 0.5]))
    X[:, 1] = _discretize(z[:, 1], np.array([-0.5, 0.5]))
    R = polychoric_covariance_matrix(X)
    gl = skein.GraphicalLasso(alpha=0.1).fit(R)
    assert gl.precision_.shape == (3, 3)
    assert np.all(np.isfinite(gl.precision_))


