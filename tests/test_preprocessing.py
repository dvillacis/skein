def test_polyserial_recovers_rho_scalar():
    """One ordinal × one continuous: should recover ρ to within 0.05
    at n=2000."""
    rng = np.random.default_rng(3)
    n = 2000
    rho = 0.5
    z = rng.multivariate_normal([0, 0], [[1, rho], [rho, 1]], size=n)
    x_ord = _discretize(z[:, 0], np.array([-1.0, 0.0, 1.0]))
    y_cont = z[:, 1]
    r = polyserial_correlation(x_ord, y_cont)
    assert isinstance(r, float)
    assert abs(r - rho) < 0.05


def test_polyserial_vectorized_shape():
    rng = np.random.default_rng(4)
    n, p_ord, p_cont = 1500, 3, 2
    z = rng.standard_normal((n, p_ord + p_cont))
    x_ord = _discretize(z[:, :p_ord], np.array([-0.5, 0.5]))
    y_cont = z[:, p_ord:]
    R = polyserial_correlation(x_ord, y_cont)
    assert R.shape == (p_ord, p_cont)
    # All uncorrelated columns → all close to 0.
    assert np.max(np.abs(R)) < 0.1


