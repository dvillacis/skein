# ---- meta tests ----------------------------------------------------------


def test_fixtures_directory_exists():
    assert FIXTURES_DIR.is_dir(), f"expected {FIXTURES_DIR} to exist"


def test_at_least_one_fixture_present():
    fixtures = sorted(FIXTURES_DIR.glob("*.json"))
    if not fixtures:
        msg = (
            "no fixtures found; run `Rscript tests/fixtures/generate.R` "
            "to generate (requires R + glmnet + ncvreg + grpreg + "
            "jsonlite + survival)"
        )
        if _REQUIRE_FIXTURES:
            pytest.fail(msg)
        pytest.skip(msg)
    assert len(fixtures) >= 1
