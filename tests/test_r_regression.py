    fix = _skipped_if_missing("grpreg_grmcp_gaussian")
    groups = fix["groups"].astype(np.int64) - 1
    model = skein.GroupMCPPathRegressor(
        groups=groups,
        weights=fix["group_multiplier"].astype(np.float64),
        gamma=fix["gamma"],
        lambdas=fix["lambdas"],
        standardize=True,
        fit_intercept=True,
        tol=1e-10,
        max_iter=50000,
        max_outer=50,
        outer_tol=1e-10,
        screening="off",
    ).fit(fix["X"], fix["y"])
    _assert_path_matches(
        model.coefs_, fix["coefs"],
        smallest_lambda_atol=1e-3,
        # Group MCP nonconvex: LLA can find different local minima
        # depending on initialization, so the active-set boundary is
        # fuzzier than for convex group lasso.
        active_set_fuzz_frac=0.40,
        # Early-path coefs at |β|~0.01 can sign-flip between LLA
        # local minima; only check signs once both solvers settle
        # on coefficients that are clearly active.
        sign_check_threshold=5e-2,
        label="grpreg grMCP vs skein",
    )


